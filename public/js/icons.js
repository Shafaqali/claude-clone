function escapeHtml(value) {
  return String(value).replace(/[&<>"']/g, char => ({
    "&": "&amp;",
    "<": "&lt;",
    ">": "&gt;",
    '"': "&quot;",
    "'": "&#039;"
  }[char]));
}

export function icon(name, className = "", label = "") {
  const body = ICONS[name] || ICONS.sparkles;
  const accessible = label
    ? `role="img" aria-label="${escapeHtml(label)}"`
    : 'aria-hidden="true"';

  return `<svg class="svg-icon ${escapeHtml(className)}" ${accessible} viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${body}</svg>`;
}

export function hydrateIcons(root = document) {
  root.querySelectorAll("[data-icon]").forEach(element => {
    element.innerHTML = icon(
      element.dataset.icon,
      element.dataset.iconClass || "",
      element.dataset.iconLabel || ""
    );
  });
}
